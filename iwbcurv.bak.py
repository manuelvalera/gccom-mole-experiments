#!/usr/bin/env python3
"""
iwbcurv.py -- internal wave beam from an oscillating tidal flow over a Gaussian
ridge, on a FULLY CURVILINEAR grid.

Reproduces the benchmark of Garcia et al. (2019) sec 3.3 (following Vitousek &
Fringer 2014), but on a grid with no straight lines in either direction rather
than the sigma grid used there.  This is the stepping stone to Monterey.

WHY CURVILINEAR AND NOT SIGMA
  A sigma grid keeps the vertical coordinate rectilinear (vertical lines stay
  vertical) and only bends the horizontal ones.  A fully general curvilinear
  grid bends both.  The grid here is generated by transfinite interpolation
  with a POSITION-DEPENDENT clustering parameter beta that differs between the
  top and bottom curves, so the xi-lines are not vertical -- measured wander
  73.8 m between top and bottom at 128x101.

CONFIGURATION (Garcia et al. 2019 sec 3.3)
  Lx = 3000 m,  D0 = 1000 m,  ridge  D = D0 - a_b exp(-x^2 / 2 L_b^2)
  a_b = 20 m,  L_b = 30 m,  N = 0.007 1/s
  forcing  u_bc = u0 sin(omega t),  u0 = 0.01 m/s at the lateral boundaries
  sponge   SL = -(u - u_bc)/tau_s * sl(r),  sl(r) = exp(-4 r / L_sl)
           tau_s = 100 s,  L_sl = Lx/10
  20 tidal periods, beam angle from the last ten.

  theory   nonhydrostatic  phi = atan( sqrt( (w/N)^2 / (1-(w/N)^2) ) )  (Eq.30)
           hydrostatic     phi = atan( w/N )                            (Eq.31)

MEASUREMENT (their method)
  Vertical location of the max rms speed in a limited horizontal window, then
  a least-squares line fit to those (x, z) maxima.  No angular averaging, so
  it is immune to the near-field contamination that biases a spherical-shell
  peak-find.

THE BED CONDITION (--bedmode, default 'constraint')
  The old 'projection' mode was a PENALTY, and the three operators involved
  were all different: robinBC2D's computational-eta normal derivative on the
  left of L, the physical contravariant flux over h_eta on the right, and
  bnd2's w = (z_xi/x_xi) u in bc_residual().  --bsc was one scalar trying to
  reconcile operators that differ point by point on a curved bed, which it
  cannot; hence a bed residual with a floor no bsc gets under, an accuracy
  lower bound and a stability upper bound, and those bounds closing at
  Lx = 6 km.
  'constraint' puts the condition INTO L instead.  D*G is empty on the ghost
  ring, so the bottom/top ghost rows are free to carry C*G, where C is the
  bnd2 relation as a matrix; the rhs there carries C*u*/dt.  Then
      C u = C(u* - dt G phi) = C u* - dt (C u*/dt) = 0
  exactly, on any grid, with nothing to tune.  Left/right keep their Robin
  rows so alpha still removes the constant nullvector.
  'post' and 'none' remain as controls and bracket the answer.

GRID DIAGNOSTICS PRINTED BEFORE ANY PHYSICS
  jacobian sign        -- must not change sign anywhere (folded grid)
  hydrostatic r_x      -- Shchepetkin & McWilliams (2003) Eq. 2.10; > 1 means
                          vertical interpolation of density becomes
                          extrapolation and the pressure-gradient force
                          degrades.  NOTE the stencil runs along ETA; getting
                          the axis wrong divides by ~0 and gives ~1e31.
  lepticity            -- Vitousek & Fringer (2011): Gamma = K*lambda^2 with
                          lambda = dx/h_e, h_e = sqrt(3)/pi * D for linear
                          stratification.  Need Gamma << 1.

USAGE
  python iwbcurv.py --mole C:/path/to/mole/src/matlab_octave --ratio 0.6
  python iwbcurv.py --mole ... --gridonly          # diagnostics, no run
  foreach ($r in 0.2,0.4,0.6,0.8) { python iwbcurv.py --mole $env:MOLE_SRC --ratio $r }
"""
