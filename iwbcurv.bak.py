NBV, U0, TAUS = 0.007, 0.01, 100.0
HERE = os.path.dirname(os.path.abspath(__file__))


def el():
    s = time.time() - T0
    h, r = divmod(int(s), 3600); m, sec = divmod(r, 60)
    return f"{h}:{m:02d}:{sec:02d}" if h else f"{m:02d}:{sec:02d}"


def beat(msg, every=None, force=False):
    now = time.time()
    if force or now - _LAST[0] >= (every or globals().get('_BEAT', 300.0)):
        _LAST[0] = now
        print(f"    [{el()} elapsed] {msg}", flush=True)


def pull(oc, nm):
    oc.eval(f"[ii,jj,vv]=find({nm}); sz=size({nm});")
    return sp.csr_matrix(
        (oc.pull('vv').ravel(),
         (oc.pull('ii').ravel().astype(int) - 1,
          oc.pull('jj').ravel().astype(int) - 1)),
        shape=tuple(oc.pull('sz').ravel().astype(int)))


def splice_bed_rows(L, CG, bedidx, eq='auto'):
    """Replace rows `bedidx` of L with the rows of CG (scaled).

    Returns (L_new, bedsc).  The caller must scale the corresponding rhs
    entries by the SAME bedsc; scaling an equation and its right-hand side by
    the same number leaves the solution unchanged, which is what makes the
    equilibration bookkeeping rather than a tuned coefficient.

    Kept at module level so it can be tested without Octave or MOLE.
    """
    nc = L.shape[0]
    nbed = CG.shape[0]
    if bedidx.size != nbed:
        raise ValueError(f"{bedidx.size} bed rows vs {nbed} constraints")
    if len(np.unique(bedidx)) != nbed:
        raise ValueError("bed row indices are not distinct")
    L = L.tocsr(); CG = CG.tocsr()
    if eq == 'auto':
        rmax = np.abs(L).max(axis=1).toarray().ravel()
        ref = np.median(rmax[rmax > 0])
        cmax = np.abs(CG).max(axis=1).toarray().ravel()
        bedsc = ref / np.maximum(cmax, 1e-300)
    else:
        bedsc = np.ones(nbed)
    keep = np.ones(nc); keep[bedidx] = 0.0
    Pb = sp.csr_matrix((np.ones(nbed), (bedidx, np.arange(nbed))),
                       shape=(nc, nbed))
    return (sp.diags(keep) @ L + Pb @ (sp.diags(bedsc) @ CG)).tocsr(), bedsc


def grid_diag(X, Z, nx, nz, phi_nh):
    """X, Z are (xi, eta).  Returns True if the grid looks usable."""
    xx = np.gradient(X, axis=0); xh = np.gradient(X, axis=1)
    zx = np.gradient(Z, axis=0); zh = np.gradient(Z, axis=1)
    J = xx * zh - xh * zx
    a_ = np.stack([xx, zx]); b_ = np.stack([xh, zh])
    c_ = (a_ * b_).sum(0) / (np.linalg.norm(a_, axis=0) * np.linalg.norm(b_, axis=0) + 1e-30)
    ang = np.degrees(np.arccos(np.clip(c_, -1, 1)))
    ok = True

    sgn = 'ALL +' if (J > 0).all() else ('ALL -' if (J < 0).all()
                                         else f'MIXED -- {int((J<0).sum())} FOLDED CELLS')
    if 'MIXED' in sgn: ok = False
    print(f"  [{el()}] jacobian  : {sgn}   |J| {np.abs(J).min():.4g} .. {np.abs(J).max():.4g}")
    print(f"  [{el()}] grid angle: {ang.min():.1f} - {ang.max():.1f} deg  (90 = orthogonal)")

    wander = np.abs(X[:, 0] - X[:, -1]).max()
    print(f"  [{el()}] xi-line wander top-to-bottom: {wander:.1f} m  "
          f"-> {'FULLY CURVILINEAR' if wander > 1 else 'still a sigma grid'}")

    # Shchepetkin & McWilliams Eq 2.10.  Columns run along ETA for (xi,eta).
    z1 = Z[:-1, :-1]; z2 = Z[:-1, 1:]; z3 = Z[1:, :-1]; z4 = Z[1:, 1:]
    den = np.abs(z4 - z3 + z2 - z1)
    rx = np.abs(z4 + z3 - z2 - z1) / np.maximum(den, 1e-12)
    if den.min() < 1e-9:
        print(f"  [{el()}] r_x       : denominator ~0 -- WRONG AXIS, ignore")
    else:
        bad = rx.max() >= 1.0
        if bad: ok = False
        print(f"  [{el()}] r_x       : max {rx.max():.3f}  median {np.median(rx):.3f}  "
              f"{'*** VIOLATED (>1) ***' if bad else 'OK (<1)'}")

    dx = LX / (nx - 1); dz = D0 / (nz - 1)
    he = np.sqrt(3) / np.pi * D0
    lam = dx / he
    print(f"  [{el()}] resolution: dx={dx:.1f} m  dz={dz:.1f} m  aspect {dz/dx:.3f}")
    print(f"  [{el()}] lepticity : h_e={he:.0f} m  lambda=dx/h_e={lam:.4f}  "
          f"Gamma~{lam**2:.4f}  {'OK (<<1)' if lam**2 < 0.1 else '*** MARGINAL ***'}")
    print(f"  [{el()}] beam      : slope {np.tan(np.radians(phi_nh)):.4f}, "
          f"bounce {D0/np.tan(np.radians(phi_nh))/1000:.2f} km, "
          f"{LX/(D0/np.tan(np.radians(phi_nh))):.1f} bounces across the domain")
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--mole', required=True)
    ap.add_argument('--Lx', type=float, default=3000.0,
                    help='domain length in m.  The beam needs at least ~1 bounce (D0/tan(phi)) to establish; at omega/N=0.2 the bounce is 4.9 km, so the default 3 km domain cannot resolve it.')
    ap.add_argument('--D0', type=float, default=1000.0,
                    help='domain depth in m')
    ap.add_argument('--nx', type=int, default=128)
    ap.add_argument('--nz', type=int, default=101)
    ap.add_argument('--ratio', type=float, default=0.6)
    ap.add_argument('--nper', type=int, default=20)
    ap.add_argument('--spp', type=int, default=60)
    ap.add_argument('--alpha', type=float, default=1e-6,
                    help='Robin coefficient on the lateral pressure rows. It only\n'
                         'regularises an otherwise pure-Neumann (singular) Poisson\n'
                         'system, so it should be as small as the factorisation\n'
                         'tolerates. The old default 1e-4 dominated the seiche\n'
                         'frequency error (+4.3e-3, growing under refinement);\n'
                         'at 1e-6 the seiche converges at second order to zero.\n'
                         'Beam angles move by <=0.1 deg between the two.')
    ap.add_argument('--N', type=float, default=NBV,
                    help='buoyancy frequency; --N 0 removes stratification '
                         'entirely (no internal waves) to test whether the '
                         'boundary layer comes from the buoyancy term')
    ap.add_argument('--bt', type=float, default=1.6, help='beta, top curve')
    ap.add_argument('--bb', type=float, default=3.2, help='beta, bottom curve')
    ap.add_argument('--win', type=float, nargs=2, default=None,
                    help='horizontal fit window in m; default is auto, set to '
                         'the first bounce so reflections are excluded')
    ap.add_argument('--grids', default=os.path.join(HERE, 'grids'))
    ap.add_argument('--forcegrid', action='store_true',
                    help='run even if the r_x check fails.  r_x is the '
                         'Shchepetkin & McWilliams criterion for the HYDROSTATIC '
                         'pressure-gradient force in sigma models; this solver is '
                         'non-hydrostatic and takes its pressure from the Poisson '
                         'projection, so r_x may not bind here.  Measured: r_x '
                         'varied 0.070-0.709 at fixed dz changes the beam angle by '
                         '<0.3 deg.  Use with the folded-Jacobian check still armed.')
    ap.add_argument('--gridonly', action='store_true',
                    help='print grid diagnostics and stop')
    ap.add_argument('--beat', type=float, default=300.0)
    ap.add_argument('--bedmode', default='constraint',
                    choices=['constraint', 'projection', 'post', 'none'],
                    help='how the bed no-flux BC is imposed.  '
                         'constraint = the bed rows of L ARE the bed condition '
                         '(hard, no free parameter).  projection = the old '
                         'robinBC-row + physical-flux-rhs penalty, needs --bsc.  '
                         'post/none are controls: post gives bed=0 with '
                         'div~2e-3, none gives div~1e-17 with bed~1.7e-1.')
    ap.add_argument('--bsc', type=float, default=1.0,
                    help='scale on the bed Neumann data (empirical). '
                         'Only used by --bedmode projection; the constraint '
                         'mode has no such coefficient by construction.')
    ap.add_argument('--seiche', type=int, nargs=2, metavar=('I', 'J'),
                    default=None,
                    help='run a free standing internal wave of horizontal mode '
                         'I and vertical mode J instead of the tidal problem, '
                         'and report the frequency error against the exact '
                         'omega = N k / sqrt(k^2 + p^2).  Requires --ab 0 '
                         '--bulge 0.  Needs no forcing, no sponge, no fit '
                         'window and no beam tracker, so it isolates the core '
                         'discretization from everything the beam angle '
                         'depends on.')
    ap.add_argument('--bulge', type=float, default=0.15,
                    help='side-wall bulge as a fraction of D0.  0 makes the '
                         'DOMAIN a rectangle while leaving the GRID curvilinear '
                         '(the xi-lines still tilt, because betaOf stretches '
                         'the top and bottom differently) -- which is what the '
                         'seiche test needs, since the analytic mode assumes a '
                         'rectangular box but we still want the metrics exercised.')
    ap.add_argument('--u0', type=float, default=0.01,
                    help='barotropic forcing amplitude in m/s (Garcia et al. '
                         'use 0.01).  Exposed to test whether the grid-'
                         'INDEPENDENT part of the beam-angle offset is finite-'
                         'amplitude: truncation error vanishes with h, a '
                         'nonlinear offset does not, but it should scale with '
                         'u0.')
    ap.add_argument('--lsl', type=float, default=0.10,
                    help='sponge width as a fraction of Lx (was hardcoded Lx/10)')
    ap.add_argument('--taus', type=float, default=100.0,
                    help='sponge relaxation time in s (was hardcoded 100)')
    ap.add_argument('--ab', type=float, default=20.0,
                    help='ridge height in m.  At the default 20 m with dz=10 m '
                         'the topography is TWO CELLS TALL, and r_x blocks '
                         'refining eta -- so this is the only handle on how '
                         'well the beam source is resolved.')
    ap.add_argument('--lb', type=float, default=30.0, help='ridge half-width in m')
    ap.add_argument('--order', type=int, default=2, choices=[2, 4, 6],
                    help='MOLE operator order k.  HANDOFF sec 5 killed the '
                         'numerical-dispersion hypothesis with a 4th-order run '
                         '-- but that was cone3d; this solver hardcoded k=2 and '
                         'the test was never run here.')
    ap.add_argument('--bedeq', default='auto', choices=['auto', 'unit'],
                    help='row equilibration of the constraint rows.  The '
                         'solution is INVARIANT to this in exact arithmetic -- '
                         'it exists only to keep splu happy, and running both '
                         'is the test that it is not a disguised --bsc.')
    ap.add_argument('--field', default='w', choices=['w', 'speed', 'ubc'],
                    help='field used for the beam track (default w)')
    ap.add_argument('--out', default=None)
    g = ap.parse_args()
    globals()['_BEAT'] = g.beat
    LX, D0 = g.Lx, g.D0
    globals()['LX'] = LX; globals()['D0'] = D0
    # gridGen resolves the boundary curves from the working directory, so the
    # geometry is handed to them through a generated geom_over.m rather than
    # by editing four .m files.
    with open(os.path.join(g.grids, 'iwbridge', 'geom_over.m'), 'w') as fh:
        fh.write("function [Lx, D0, ab, Lb] = geom_over()\n"
                 f"    Lx = {LX}; D0 = {D0}; ab = {g.ab}; Lb = {g.lb};\nend\n")

    # --N 0 removes stratification entirely.  The forcing frequency still
    # needs a reference N to stay fixed, so omega is set from the default.
    Nb = g.N
    om = g.ratio * NBV
    T = 2 * np.pi / om
    phi_nh = np.degrees(np.arctan(np.sqrt(g.ratio**2 / (1 - g.ratio**2))))
    phi_h = np.degrees(np.arctan(g.ratio))
    print(f"\n=== iwbcurv  omega/N={g.ratio}  {g.nx}x{g.nz}  {g.nper} periods  "
          f"Lx={LX/1000:.1f} km  D0={D0:.0f} m  k={g.order}  alpha={g.alpha:.0e}  "
          f"FULLY CURVILINEAR ===")
    print(f"  theory: nonhydrostatic {phi_nh:.2f} deg (Eq.30)   "
          f"hydrostatic {phi_h:.2f} deg (Eq.31)")

    # Fit window.  The column-max tracker follows the brightest feature, so it
    # must see the PRIMARY beam only.  Past the first bounce the field is the
    # beam superposed on its surface/bottom reflections and the brightest
    # column feature is whichever reflection happens to win -- measured as
    # max/mean dropping from 19 (0.6 bounces) to ~5 (2-4 bounces), with the
    # tracked angle going with it.  Default window = 15..70% of one bounce.
    bounce = D0 / np.tan(np.radians(phi_nh))
    if g.win is None:
        g.win = [max(0.15 * bounce, 3 * LX / g.nx), min(0.70 * bounce, 0.45 * LX)]
        print(f"  window: auto [{g.win[0]:.0f}, {g.win[1]:.0f}] m "
              f"(bounce = {bounce:.0f} m; keeps the fit inside the first bounce)")
    else:
        print(f"  window: [{g.win[0]:.0f}, {g.win[1]:.0f}] m  "
              f"(bounce = {bounce:.0f} m)")

    print(f"  [{el()}] generating grid (TFI, position-dependent beta) ...", flush=True)
    from oct2py import Oct2Py           # imported here so this module can be
    oc = Oct2Py()                       # imported without Octave, for tests; oc.eval("warning('off','all'); more off;")
    # Octave's addpath does NOT error on a directory that does not exist, and
    # a MOLE path pointing one level too high (the repo root, or src/) fails
    # much later as "error: 'gridGen' undefined" from inside oc.eval, which
    # names neither the path nor the real problem.  Check it here instead.
    _need = ['gridGen.m', 'grad2DCurv.m', 'div2DCurv.m', 'robinBC2D.m',
             'interpol2D.m', 'jacobian2D.m']
    _miss = [f for f in _need if not os.path.isfile(os.path.join(g.mole, f))]
    if _miss:
        oc.exit()
        print(f"\n  *** --mole does not look like MOLE's src/matlab_octave:\n"
              f"      {g.mole}\n"
              f"      missing: {', '.join(_miss)}\n"
              f"      It must be the directory CONTAINING gridGen.m -- usually\n"
              f"      <mole-repo>/src/matlab_octave, not the repo root.\n")
        for _root, _dirs, _files in os.walk(os.path.abspath(os.path.join(g.mole, '..', '..'))):
            if 'gridGen.m' in _files:
                print(f"      found gridGen.m in: {_root}\n")
                break
        return
    oc.addpath(g.mole); oc.addpath(os.path.join(g.grids, 'iwbridge'))
    here = os.getcwd(); os.chdir(g.grids)
    try:
        oc.eval(f"global BT BB BULGE; BT={g.bt}; BB={g.bb}; BULGE={g.bulge};")
        oc.eval(f"cd('{g.grids.replace(os.sep,'/')}'); "
                f"[X,Z]=gridGen('TFI','iwbridge',{g.nx},{g.nz},false);")
    finally:
        os.chdir(here)
    X = oc.pull('X'); Z = oc.pull('Z')

    ok = grid_diag(X, Z, g.nx, g.nz, phi_nh)
    if g.gridonly:
        oc.exit()
        print("\n  (--gridonly: stopping here)\n"); return
    if not ok and not g.forcegrid:
        oc.exit()
        print("\n  *** grid diagnostics failed -- fix the grid before running ***\n")
        return
    if not ok:
        print("  [%s] --forcegrid: grid check FAILED, running anyway" % el())

    # MOLE wants (eta, xi); gridGen returns (xi, eta).  Transposing two axes is
    # an ODD permutation and flips the Jacobian sign, so this must be explicit.
    XM = X.T.copy(); ZM = Z.T.copy()
    m, n = g.nx - 1, g.nz - 1
    dxr, dzr = LX / m, D0 / n
    oc.push('Xm', XM); oc.push('Zm', ZM)
    oc.eval(f"k={g.order}; m={m}; n={n}; dx={dxr}; dz={dzr};")
    oc.eval("J2=jacobian2D(k,Xm,Zm);")
    J2 = oc.pull('J2').ravel()
    print(f"  [{el()}] MOLE jacobian2D on the transposed grid: "
          f"{'ALL +' if (J2>0).all() else ('ALL -' if (J2<0).all() else 'MIXED')}")
    oc.eval("G=grad2DCurv(k,Xm,Zm); D=div2DCurv(k,Xm,Zm); "
            f"B=robinBC2D(k,m,dx,n,dz,{g.alpha},1); "
            "Ic=interpol2D(m,n,0.5,0.5); Idf=interpolD2D(m,n,0.5,0.5);")
    G, D, B, Ic, Idf = [pull(oc, s) for s in ('G', 'D', 'B', 'Ic', 'Idf')]
    oc.exit()

    nu_, nw_ = (m + 1) * n, m * (n + 1)
    nc = (m + 2) * (n + 2)
    # L is assembled further down, AFTER the bed constraint operator C exists:
    # in --bedmode constraint the eta-boundary rows of L are rows of C*G, so
    # the matrix cannot be built until C is.

    # physical coordinates of the faces (arrays are (eta, xi) from here on)
    # Face coordinates.  ARRAY ORDER MATTERS: u is indexed reshape(n, m+1) and
    # w is reshape(n+1, m), both eta-major with xi fastest, so these must be
    # ravelled directly.  A stray .T scrambles the sponge across the wrong axis
    # and the forcing lands in the wrong rows -- symptom is a barotropic flow
    # 5x stronger at the top and bottom than at mid-depth, when it should be
    # nearly depth-uniform.
    Zf = 0.5 * (ZM[:, :-1] + ZM[:, 1:]); Xf = 0.5 * (XM[:, :-1] + XM[:, 1:])
    xw = Xf.ravel(); zw = Zf.ravel()
    Xu = 0.5 * (XM[:-1, :] + XM[1:, :]); xu = Xu.ravel()
    assert xu.size == nu_ and xw.size == nw_, "face coordinate ordering mismatch"

    Lsl = g.lsl * LX
    slu = np.exp(-4 * np.minimum(np.abs(xu + LX/2), np.abs(xu - LX/2)) / Lsl)
    slw = np.exp(-4 * np.minimum(np.abs(xw + LX/2), np.abs(xw - LX/2)) / Lsl)

    Ic_z = Ic[nu_:, :].tocsr()
    Idf_w = Idf[:, nu_:].tocsr()
    Idf_u = Idf[:, :nu_].tocsr()

    # ------------------------------------------------------------------
    # Bottom / top no-normal-flow.  WITHOUT THIS THERE IS NO INTERNAL TIDE:
    # the barotropic flow must follow the seabed, w = u dh/dx, and that
    # conversion at the topography is what generates the beam.  With no
    # condition the flow slides through the ridge and feels nothing.
    #
    # On a curvilinear grid the eta = const surface has tangent r_xi =
    # (x_xi, z_xi), so its normal is (-z_xi, x_xi) and no-flux reads
    #     -z_xi u + x_xi w = 0   ->   w = (z_xi / x_xi) u
    # which is w = u dh/dx written contravariantly.  u is averaged in from
    # the x-faces either side of each bottom/top z-face.
    # ------------------------------------------------------------------
    iu2 = np.arange(nu_).reshape(n, m + 1)      # (eta, xi)
    iw2 = np.arange(nw_).reshape(n + 1, m)
    bnd2 = []
    for jp_, jc in ((0, 0), (n, n - 1)):
        zx_ = np.gradient(ZM[jp_, :])           # dz/dxi along that boundary
        xx_ = np.gradient(XM[jp_, :])
        zc_ = 0.5 * (zx_[:-1] + zx_[1:]); xc_ = 0.5 * (xx_[:-1] + xx_[1:])
        ratio_ = zc_ / np.where(np.abs(xc_) < 1e-12, 1e-12, xc_)
        bnd2.append((iw2[jp_, :], iu2[jc, :-1], iu2[jc, 1:], ratio_))
    print(f"  [{el()}] bottom/top BC: w = (z_xi/x_xi) u   "
          f"|slope| max {max(np.abs(b[3]).max() for b in bnd2):.4f}")

    def apply_bed(uu, ww):
        for tgt, s1, s2, rat in bnd2:
            ww[tgt] = rat * 0.5 * (uu[s1] + uu[s2])
        return ww

    # ------------------------------------------------------------------
    # C -- the bed condition as a MATRIX, built from the same bnd2 arrays that
    # bc_residual() measures.  This is the whole point: the equation solved and
    # the residual reported must be the SAME operator.  In the penalty scheme
    # they were three different ones -- robinBC2D's computational-eta normal
    # derivative on the left, the physical contravariant flux over hec on the
    # right, and bnd2's w = rat*avg(u) in the check -- and --bsc was a single
    # scalar trying to reconcile operators that differ point by point.  It
    # cannot, which is why the bed residual has a floor no bsc gets under.
    #
    #     C [u; w] = 0    one row per bed/top face:
    #     w_face - (z_xi/x_xi) * 0.5 * (u_left + u_right) = 0
    #
    # ARRAY ORDER: bnd2 already holds flat indices into the eta-major, xi-
    # fastest u and w vectors (iu2 = arange(nu_).reshape(n, m+1), iw2 =
    # arange(nw_).reshape(n+1, m)).  C is assembled from those indices
    # directly, so there is no reshape anywhere in here to get wrong -- and
    # the check below fails loudly if that is ever untrue.
    # ------------------------------------------------------------------
    _r, _rows, _cols, _vals = 0, [], [], []
    for tgt, s1, s2, rat in bnd2:
        rr_ = np.arange(_r, _r + tgt.size)
        _rows += [rr_, rr_, rr_]
        _cols += [nu_ + tgt, s1, s2]
        _vals += [np.ones(tgt.size), -0.5 * rat, -0.5 * rat]
        _r += tgt.size
    nbed = _r
    C = sp.csr_matrix((np.concatenate(_vals),
                       (np.concatenate(_rows), np.concatenate(_cols))),
                      shape=(nbed, nu_ + nw_))

    # Fails loudly BEFORE the feature, not after (the sponge and the r_x
    # stencil both cost hours because the check came second).
    _rg = np.random.default_rng(7)
    _uu, _ww = _rg.standard_normal(nu_), _rg.standard_normal(nw_)
    _ref = np.concatenate([_ww[t_] - r_ * 0.5 * (_uu[a_] + _uu[b_])
                           for t_, a_, b_, r_ in bnd2])
    _err = np.abs(_ref - C @ np.concatenate([_uu, _ww])).max()
    print(f"  [{el()}] C: {nbed} bed rows, {C.nnz} nnz; "
          f"agrees with bc_residual loop to {_err:.2e}")
    if _err > 1e-12:
        raise SystemExit("  *** C does not reproduce the bnd2 residual -- "
                         "index/array-order bug, stopping ***")

    # ------------------------------------------------------------------
    # Bed condition INSIDE the projection.
    #
    # Patching w after the solve satisfies the bed exactly and leaves
    # div(u) ~ 2e-3 every step, which compounds through gp and destabilises
    # the run.  The standard fix is to carry the condition as inhomogeneous
    # Neumann data on the pressure: we want n.u^{n+1} = 0 with
    # u^{n+1} = u* - dt grad(phi), so
    #     n.u* - dt dphi/dn = 0   ->   dphi/dn = (n.u*) / dt
    # and the boundary rows of the RHS carry that instead of zero.  Then the
    # PROJECTED field satisfies both conditions by construction.
    #
    # n = (-z_xi, x_xi) for an eta = const surface.  The scale factor bsc is
    # determined empirically from the consistency check rather than derived,
    # because MOLE's robinBC2D expresses dphi/dn in computational units while
    # grad2DCurv returns a physical gradient.
    # ------------------------------------------------------------------
    ic2 = np.arange(nc).reshape(n + 2, m + 2)
    bedrows, bednrm = [], []
    for jg, jp_, jc, sgn in ((0, 0, 0, -1.0), (n + 1, n, n - 1, +1.0)):
        # tangent along the boundary and the local normal
        zx_ = np.gradient(ZM[jp_, :]); xx_ = np.gradient(XM[jp_, :])
        zc_ = 0.5 * (zx_[:-1] + zx_[1:]); xc_ = 0.5 * (xx_[:-1] + xx_[1:])
        nx_ = -zc_; nz_ = xc_
        ln = np.hypot(nx_, nz_); nx_ = nx_ / ln; nz_ = nz_ / ln
        # PER-FACE metric factor.  robinBC2D expresses dphi/dn in COMPUTATIONAL
        # units; grad2DCurv returns a PHYSICAL gradient.  The conversion is the
        # physical distance spanned by one eta step at this xi station, which
        # varies point-to-point on a curvilinear boundary -- so a single global
        # scalar can only ever fit it on average (measured floor: bed residual
        # 3.2e-02 with the best global constant).  h_eta = |r_eta| locally.
        j2 = min(jp_ + 1, n); j1 = max(jp_ - 1, 0)
        dxe = 0.5 * (XM[j2, :] - XM[j1, :]) * (2.0 / max(j2 - j1, 1))
        dze = 0.5 * (ZM[j2, :] - ZM[j1, :]) * (2.0 / max(j2 - j1, 1))
        he = np.hypot(dxe, dze)
        hec = 0.5 * (he[:-1] + he[1:])
        met = sgn / np.maximum(hec, 1e-12)
        bedrows.append(ic2[jg, 1:-1])
        bednrm.append((nx_, nz_, iu2[jc, :-1], iu2[jc, 1:], iw2[jp_, :], met))

    # ------------------------------------------------------------------
    # ROW REPLACEMENT.
    #
    # D*G is zero on the ghost ring -- those rows exist only to carry boundary
    # data, which is why L = D*G + robinBC works at all.  So the bottom/top
    # ghost rows are free to carry the bed condition instead of a Robin row:
    #
    #     L[bedidx, :] = C*G          rhs[bedidx] = C*u* / dt
    #
    # and then, identically,
    #
    #     C u = C(u* - dt*G*phi) = C u* - dt*(C u*/dt) = 0
    #
    # to solver tolerance, for any grid, with nothing to tune.  The left and
    # right ghost rows keep their Robin rows, so alpha still removes the
    # constant nullvector and the system stays nonsingular -- do not drop it.
    #
    # Row count is exact: m*n interior + 2m bed + 2n sides + 4 corners = nc.
    # ------------------------------------------------------------------
    DG = (D @ G).tocsr()
    L = (DG + B).tocsr()
    bedidx = np.concatenate(bedrows)
    bedsc = np.ones(nbed)

    if g.bedmode == 'constraint':
        if bedidx.size != nbed:
            raise SystemExit(f"  *** {bedidx.size} bed ghost rows vs {nbed} "
                             f"constraints -- pairing is wrong, stopping ***")
        leak = np.abs(DG[bedidx]).max() if DG[bedidx].nnz else 0.0
        print(f"  [{el()}] D*G on the bed ghost rows: max|entry| {leak:.2e} "
              f"{'(empty, as expected)' if leak < 1e-12 else '*** NOT EMPTY -- a real equation is being discarded ***'}")

        # Row equilibration only.  D*G rows scale like 1/dx^2 and C*G rows like
        # 1/dx, so without it splu sees orders of magnitude of row imbalance.
        # Scaling a row AND its rhs by the same number leaves the solution
        # unchanged -- that is what makes this not a --bsc, and --bedeq unit is
        # the test of it.
        L, bedsc = splice_bed_rows(L, C @ G, bedidx, g.bedeq)
        print(f"  [{el()}] constraint row equilibration: "
              f"x{bedsc.min():.2e} .. {bedsc.max():.2e} "
              f"(cancels out of the solution; check with --bedeq unit)")

    L = L.tocsc()
    print(f"  [{el()}] L: n={nc} nnz={L.nnz} ({L.nnz/nc:.1f}/row) "
          f"bedmode={g.bedmode}, factorising ...", flush=True)
    t = time.time(); lu = spl.splu(L)
    print(f"  [{el()}] splu {time.time()-t:.1f}s")

    # Static validation of the whole projection, before a single timestep.
    # A random field is projected and BOTH conditions are measured.  If the
    # constraint mode is right this reports bed ~1e-16 here, and no amount of
    # time stepping can be needed to find that out.
    fk = np.random.default_rng(1).standard_normal(G.shape[0])
    rr = D @ fk
    if g.bedmode == 'constraint':
        rr[bedidx] = bedsc * (C @ fk)
    pf = fk - G @ lu.solve(rr)
    dv = np.linalg.norm(D @ pf) / np.linalg.norm(rr)
    bd = np.abs(C @ pf).max() / np.abs(fk).max()
    print(f"  [{el()}] static projection test: div {dv:.2e} "
          f"{'OK' if dv < 1e-8 else '*** BROKEN ***'}   "
          f"bed {bd:.2e} "
          f"{'OK' if bd < 1e-8 else ('*** BROKEN ***' if g.bedmode == 'constraint' else '(not enforced in this mode)')}")
    if g.bedmode == 'constraint' and not (dv < 1e-8 and bd < 1e-8):
        raise SystemExit("  *** the constraint does not hold on a static "
                         "projection -- nothing downstream is worth running ***")

    def bed_rhs(us_, ws_, rhs_, bsc):
        for tgt, (nx_, nz_, s1, s2, sw, met) in zip(bedrows, bednrm):
            un = nx_ * 0.5 * (us_[s1] + us_[s2]) + nz_ * ws_[sw]
            rhs_[tgt] = bsc * met * un / dt
        return rhs_

    # ------------------------------------------------------------------
    # SEICHE: the solver measured against an exact answer.
    #
    # The beam angle converges at first order to a nonzero limit, and seven
    # candidate causes have been eliminated.  The problem with continuing to
    # test it is that it depends on the ridge sampling, the sponge, the fit
    # window and the tracker simultaneously, so every test so far has been
    # confounded by at least one of them.
    #
    # A free standing internal wave in a flat rectangular box has an exact
    # frequency, omega = N k / sqrt(k^2 + p^2), with k = I pi / Lx and
    # p = J pi / D0.  No forcing, no sponge, no topography, no tracker: the
    # only thing left is the discretization.  The GRID is still curvilinear
    # (--bulge 0 makes the DOMAIN a rectangle, but the xi-lines still tilt by
    # 148 m because betaOf stretches top and bottom differently), so the
    # metrics are still exercised.
    #
    #   u = -(W p / k) sin(k x') cos(p z')     zero at x' = 0, Lx
    #   w =            cos(k x') sin(p z')     zero at z' = 0, D0
    #
    # which is divergence-free analytically; it is projected once so that it
    # is divergence-free DISCRETELY before stepping.
    # ------------------------------------------------------------------
    if g.seiche:
        I_, J_ = g.seiche
        if abs(g.ab) > 1e-12 or abs(g.bulge) > 1e-12:
            print("\n  *** --seiche needs a rectangular domain: "
                  "--ab 0 --bulge 0 ***\n")
            return
        Zu = 0.5 * (ZM[:-1, :] + ZM[1:, :])
        kx, pz = I_ * np.pi / LX, J_ * np.pi / D0
        om_ex = Nb * kx / np.hypot(kx, pz)
        T_ex = 2 * np.pi / om_ex
        dt = T_ex / g.spp
        nt = int(g.nper * T_ex / dt)
        print(f"  [{el()}] seiche mode ({I_},{J_}): exact omega = {om_ex:.6e} 1/s"
              f"  T = {T_ex:.2f} s   dt = {dt:.3f} s   {nt} steps")

        xp_u = Xu.ravel() + LX / 2.0; zp_u = Zu.ravel() + D0
        xp_w = Xf.ravel() + LX / 2.0; zp_w = Zf.ravel() + D0
        u = -(pz / kx) * np.sin(kx * xp_u) * np.cos(pz * zp_u)
        w = np.cos(kx * xp_w) * np.sin(pz * zp_w)
        wref = w.copy()
        b = np.zeros(nc); gp = np.zeros(nu_ + nw_)

        # one projection so the initial field is discretely divergence-free
        usw = np.concatenate([u, w])
        rhs = (D @ usw)
        rhs[bedidx] = bedsc * (C @ usw)
        phi = lu.solve(rhs); gph = G @ phi
        u -= gph[:nu_]; w -= gph[nu_:]
        print(f"  [{el()}] initial field projected: "
              f"div {np.abs(D @ np.concatenate([u, w])).max():.2e}  "
              f"bed {np.abs(C @ np.concatenate([u, w])).max():.2e}")

        nrm = float(wref @ wref)
        a_t = np.empty(nt + 1); a_t[0] = (wref @ w) / nrm
        for it in range(1, nt + 1):
            us = u - dt * gp[:nu_]
            ws = w - dt * gp[nu_:] + dt * (Ic_z @ b)
            usw = np.concatenate([us, ws])
            rhs = (D @ usw) / dt
            rhs[bedidx] = bedsc * (C @ usw) / dt
            phi = lu.solve(rhs); gph = G @ phi
            u = us - dt * gph[:nu_]; w = ws - dt * gph[nu_:]
            gp = gp + gph
            b = b - dt * Nb**2 * (Idf_w @ w)
            a_t[it] = (wref @ w) / nrm
            if not np.isfinite(a_t[it]) or abs(a_t[it]) > 1e3:
                print(f"\n  *** seiche DIVERGED at step {it} ***\n"); return

        # frequency from zero crossings of the modal amplitude, linearly
        # interpolated.  Counting many periods averages the per-crossing error
        # down; a single period would not resolve a 1e-4 relative difference.
        s_ = np.sign(a_t); idx = np.where(s_[:-1] * s_[1:] < 0)[0]
        if len(idx) < 3:
            print("  *** fewer than 3 zero crossings; raise --nper ***"); return
        tc = np.array([(i + a_t[i] / (a_t[i] - a_t[i + 1])) * dt for i in idx])
        half = np.diff(tc)
        om_num = np.pi / half.mean()
        err = (om_num - om_ex) / om_ex
        print(f"  [{el()}] crossings {len(tc)}  half-period "
              f"{half.mean():.4f} +/- {half.std():.4f} s")
        print(f"\n  SEICHE  omega_num = {om_num:.6e}   exact = {om_ex:.6e}"
              f"   relative error = {err:+.4e}")
        print(f"  grid {g.nx}x{g.nz}  dx={LX/(g.nx-1):.2f} m  dz={D0/(g.nz-1):.2f} m"
              f"  spp={g.spp}\n")
        return

    dt = T / g.spp; nt = int(g.nper * T / dt)
    print(f"  [{el()}] dt={dt:.2f} s  ({nt} steps, {g.spp}/period)  T={T:.1f} s")

    # Sponge stability.  The relaxation -(u-ubc)/taus*sl is EXPLICIT, so
    # dt/taus is a stability number and the sponge coefficient caps at 1 in
    # the sponge core.  Measured: dt/taus = 1.0 still runs, 2.5 blows up to
    # max|u| = 1.0, 5.0 to 5.1e+08 -- the sponge drives the divergence itself,
    # the same mechanism as HANDOFF sec 4 item 4.  There was no guard, so this
    # looked like a physics blow-up.  Refuse rather than run and mislead.
    sponge_cfl = dt / g.taus
    print(f"  [{el()}] sponge: Lsl={g.lsl*LX:.0f} m ({g.lsl:.2f} Lx)  "
          f"taus={g.taus:.1f} s  taus/T={g.taus/T:.4f}  dt/taus={sponge_cfl:.2f} "
          f"{'OK' if sponge_cfl <= 0.5 else ('MARGINAL' if sponge_cfl <= 1.0 else '*** UNSTABLE ***')}")
    if sponge_cfl > 1.0:
        print(f"\n  *** dt/taus = {sponge_cfl:.2f} > 1: the sponge relaxation is "
              f"explicit and will drive a blow-up.\n      Raise --taus above "
              f"{dt:.1f} s or raise --spp above {int(np.ceil(T/g.taus))}.\n")
        return

    # Instantaneous snapshot at the phase where u_bc = 0, matching Garcia et
    # al. Fig 8 (t = 19.5T).  An rms average over ten periods sums the primary
    # beam AND every reflection with equal weight, so weak reflections build
    # into a visible family of arms; a single-phase snapshot lets the primary
    # beam dominate and shows the red/blue phase banding across it.
    snap_u = None; snap_t = -1.0
    u = np.zeros(nu_); w = np.zeros(nw_); b = np.zeros(nc)
    gp = np.zeros(nu_ + nw_); acc = np.zeros(nc); nacc = 0
    # Growth-based divergence detector.  Testing isfinite alone is useless: a
    # run can grow 14 orders of magnitude and still report a plausible angle,
    # because a blow-up has a huge peak-to-mean ratio by construction.  The
    # forcing amplitude u0 is the natural yardstick -- a linear internal tide
    # driven at u0 cannot legitimately exceed a few times u0.
    ulim = 50.0 * g.u0
    # ------------------------------------------------------------------
    # Consistency check.  After the projection the velocity must satisfy BOTH
    #   (a) div(u) = 0                          -- the projection's job
    #   (b) w = (z_xi/x_xi) u at the bed        -- the no-flux condition
    # Applying (b) AFTER the projection satisfies (b) exactly and breaks (a):
    # each step injects a little divergence at the seabed, which accumulates
    # through gp = gp + gphi.  That is a slow compounding feedback -- measured
    # e-folding ~2-3e4 s, invisible over 20 short-period forcing cycles and
    # fatal over 40.  Reported every heartbeat so a run cannot look healthy
    # while quietly violating one of the two conditions.
    # ------------------------------------------------------------------
    def bc_residual(uu, ww):
        r_div = np.linalg.norm(D @ np.concatenate([uu, ww]))
        scale = np.linalg.norm(uu) + 1e-300
        r_bed = 0.0
        for tgt, s1, s2, rat in bnd2:
            r_bed = max(r_bed, np.abs(ww[tgt] - rat*0.5*(uu[s1] + uu[s2])).max())
        return r_div/scale, r_bed/(np.abs(uu).max() + 1e-300)

    t0 = time.time(); beat(f"time loop: {nt} steps", force=True)
    for it in range(1, nt + 1):
        t = it * dt
        ubc = g.u0 * np.sin(om * t)
        us = u - dt * gp[:nu_] - dt * (u - ubc) / g.taus * slu
        ws = w - dt * gp[nu_:] + dt * (Ic_z @ b) - dt * w / g.taus * slw
        usw = np.concatenate([us, ws])
        rhs = (D @ usw) / dt
        if g.bedmode == 'constraint':
            rhs[bedidx] = bedsc * (C @ usw) / dt
        elif g.bedmode == 'projection':
            rhs = bed_rhs(us, ws, rhs, g.bsc)
        gphi = G @ lu.solve(rhs)
        u = us - dt * gphi[:nu_]
        w = ws - dt * gphi[nu_:]
        if g.bedmode == 'post':
            w = apply_bed(u, w)
        gp = gp + gphi
        wc = Idf_w @ w
        b = b - dt * Nb**2 * wc
        if it % max(1, nt // 5) == 0:
            rd, rb = bc_residual(u, w)
            if rd < 1e-8 and rb < 1e-8:
                verdict = 'BOTH OK'
            elif rd >= 1e-8 and rb >= 1e-8:
                verdict = 'BOTH VIOLATED'
            elif rd >= 1e-8:
                verdict = 'div VIOLATED'
            elif g.bedmode == 'constraint':
                verdict = 'bed VIOLATED -- the constraint is not holding'
            else:
                verdict = 'bed approx (penalty)'
            print("    [%s] consistency: div %.2e  bed %.2e   %s"
                  % (el(), rd, rb, verdict), flush=True)
        if it % 20 == 0:
            mu = np.abs(u).max()
            if (not np.isfinite(mu)) or mu > ulim:
                print(f"\n  *** DIVERGED at t/T={t/T:.2f}: max|u|={mu:.3e}, "
                      f"{mu/g.u0:.1f}x the forcing amplitude u0={g.u0} ***")
                print(f"  (no beam angle reported -- the field is not physical)\n")
                return
            rate = (time.time() - t0) / it
            beat(f"step {it}/{nt} ({100*it/nt:.0f}%)  ETA {(nt-it)*rate/60:.1f} min")
        # nearest step to each u_bc = 0 crossing in the second half
        if t / T > g.nper - 10 and abs(np.sin(om * t)) < np.sin(om * dt):
            snap_u = (Idf_u @ u).copy(); snap_w = (Idf_w @ w).copy(); snap_t = t
        if t / T > g.nper - 10:
            # Which field tracks the beam?
            #   'w'      vertical velocity -- the barotropic tide is horizontal
            #            and depth-independent, so w is almost purely baroclinic
            #   'speed'  |u|^2+|w|^2 -- swamped by the barotropic u (~5e-3)
            #            which is several times the beam signal (~1e-3)
            #   'ubc'    u with the depth mean removed = baroclinic u
            uc_ = Idf_u @ u
            if g.field == 'w':
                acc += wc**2
            elif g.field == 'speed':
                acc += uc_**2 + wc**2
            else:                                   # 'ubc'
                U2 = uc_.reshape(m+2, n+2)
                acc += (U2 - U2.mean(axis=1, keepdims=True)).ravel()**2 + wc**2
            nacc += 1
        if it % max(1, nt // 5) == 0:
            print(f"    [{el()}] t/T={t/T:5.1f}  max|u|={np.abs(u).max():.3e}  "
                  f"max|w|={np.abs(w).max():.3e}", flush=True)
            _LAST[0] = time.time()

    # acc is flattened X-FASTEST, so this is reshape(n+2, m+2).  Writing
    # reshape(m+2, n+2).T gives the right SHAPE but scrambles the data --
    # the same transposition trap that flips the Jacobian sign and blows up
    # the r_x stencil.  A scrambled field shows no beam no matter what.
    rms = np.sqrt(acc / max(nacc, 1)).reshape(n + 2, m + 2)

    # Beam fit: vertical location of the rms max per column, then least
    # squares to those (x, z) maxima.
    #
    # On a FULLY CURVILINEAR grid each column's x changes with depth (the
    # xi-lines wander, 73.8 m at 128x101), and the vertical spacing is not a
    # linear fraction of the local depth.  So the physical cell-centre
    # coordinates must be used directly -- reconstructing them from a single
    # boundary row plus a sigma-like fraction is only valid on a sigma grid
    # and puts every point in the wrong place.
    Xcen = np.zeros((n + 2, m + 2)); Zcen = np.zeros((n + 2, m + 2))
    Xin = 0.25*(XM[:-1, :-1] + XM[1:, :-1] + XM[:-1, 1:] + XM[1:, 1:])
    Zin = 0.25*(ZM[:-1, :-1] + ZM[1:, :-1] + ZM[:-1, 1:] + ZM[1:, 1:])
    Xcen[1:-1, 1:-1] = Xin; Zcen[1:-1, 1:-1] = Zin
    for Ac in (Xcen, Zcen):                       # fill the ghost ring
        Ac[0, :] = Ac[1, :]; Ac[-1, :] = Ac[-2, :]
        Ac[:, 0] = Ac[:, 1]; Ac[:, -1] = Ac[:, -2]

    pts = []
    for j in range(1, m + 1):
        col = rms[1:-1, j]
        if not np.isfinite(col).any() or col.max() <= 0:
            continue
        k = int(np.nanargmax(col)) + 1
        xv, zv = Xcen[k, j], Zcen[k, j]
        if not (g.win[0] <= abs(xv) <= g.win[1]):
            continue
        pts.append((abs(xv), zv))
    if len(pts) < 4:
        print("  too few points for a beam fit"); return
    P = np.array(pts)
    A = np.vstack([P[:, 0], np.ones(len(P))]).T
    slope, icpt = np.linalg.lstsq(A, P[:, 1], rcond=None)[0]
    meas = np.degrees(np.arctan(abs(slope)))
    res = P[:, 1] - A @ [slope, icpt]
    print(f"\n  fit over |x| in [{g.win[0]:.0f},{g.win[1]:.0f}] m, {len(P)} points, "
          f"rms residual {np.sqrt(np.mean(res**2)):.1f} m")
    print(f"  field: max/mean {rms[1:-1,1:-1].max()/rms[1:-1,1:-1].mean():.1f}  "
          f"(>>5 means a coherent beam; ~5 means reflections dominate)")
    print(f"  BEAM ANGLE  measured {meas:.2f}   nonhydrostatic {phi_nh:.2f}   "
          f"hydrostatic {phi_h:.2f}   error {meas-phi_nh:+.2f} deg "
          f"({100*(meas-phi_nh)/phi_nh:+.1f}%)")
    if g.out:
        sv = dict(rms=rms, X=XM, Z=ZM, pts=P, ratio=g.ratio, u0=g.u0)
        if snap_u is not None:
            sv['snap_u'] = snap_u.reshape(n + 2, m + 2)
            sv['snap_w'] = snap_w.reshape(n + 2, m + 2)
            sv['snap_tT'] = snap_t / T
        np.savez_compressed(g.out, **sv)
        print(f"  saved {g.out}")
    print(f"\n  total wall time {el()}\n")


