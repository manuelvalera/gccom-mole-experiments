def el():
    s = time.time() - T0
    h, r = divmod(int(s), 3600)
    m, sec = divmod(r, 60)
    return f"{h}:{m:02d}:{sec:02d}" if h else f"{m:02d}:{sec:02d}"


def beat(msg, every=None, force=False):
    now = time.time()
    if force or now - _LAST[0] >= (every or globals().get('_BEAT', 300.0)):
        _LAST[0] = now
        print(f"    [{el()} elapsed] {msg}", flush=True)


# ---------------------------------------------------------------------------
# Grid / operator cache.
#
# A profile at 896x351 put ~197 s of a 324 s run in Octave's gridGen, and the
# operators add ~10 s more -- rebuilt identically on every run of a sweep. The
# key covers everything that can change the result: grid size, geometry, the
# stretching and bulge, and a hash of every .m file under MOLE's source tree
# and the grid-definition directory, so editing MOLE or a boundary curve
# invalidates the cache automatically. Delete the cache directory to force a
# rebuild; --no-cache bypasses it.
# ---------------------------------------------------------------------------
def _tree_hash(roots):
    h = hashlib.sha1()
    for root in roots:
        for dp, dn, fn in os.walk(root):
            dn.sort()
            for f in sorted(fn):
                if f.endswith('.m') and f != 'geom_over.m':
                    h.update(os.path.relpath(os.path.join(dp, f), root).encode())
                    with open(os.path.join(dp, f), 'rb') as fh:
                        h.update(fh.read())
    return h.hexdigest()


def _key(d):
    return hashlib.sha1(json.dumps(d, sort_keys=True).encode()).hexdigest()[:16]


def _atomic_savez(path, **arrays):
    os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
    tmp = path[:-4] + '.partial.npz'
    np.savez(tmp, **arrays)
    os.replace(tmp, path)           # a crash mid-write never leaves a bad cache


def _pack_ops(mats, J2):
    d = {'J2': J2}
    for k, M in mats.items():
        M = sp.csr_matrix(M)
        d[k + '_data'], d[k + '_indices'] = M.data, M.indices
        d[k + '_indptr'], d[k + '_shape'] = M.indptr, np.array(M.shape)
    return d


def _unpack_ops(z, names):
    mats = [sp.csr_matrix((z[k + '_data'], z[k + '_indices'], z[k + '_indptr']),
                          shape=tuple(z[k + '_shape'])) for k in names]
    return mats, z['J2']


# ---------------------------------------------------------------------------
# PARDISO, as a drop-in for SuperLU's factor-once / solve-many interface.
#
# SuperLU's solve is single-threaded; MKL PARDISO's is multithreaded. Same
# double precision. The solve-only path skips pypardiso's per-call check that
# the matrix is unchanged (an O(nnz) comparison), which is safe here because L
# is fixed for the whole run. Thread count follows MKL_NUM_THREADS.
# ---------------------------------------------------------------------------
class _CudssLU:
    """Factor once on the GPU with NVIDIA cuDSS (via nvmath-python), solve many.

    Mirrors exactly the call sequence verified in solver_bench.py: plan and
    factorize once, then for every right-hand side reset_operands(b=...) and
    solve(). FP64 throughout -- the benchmark showed FP32 on this matrix loses
    the accuracy the projection needs. Operands stay host (numpy) arrays, so the
    PCIe transfers are included in the measured ~6 ms per solve.
    """
    def __init__(self, A, device=False):
        from nvmath.sparse.advanced import DirectSolver
        Ah = sp.csr_matrix(A, dtype=np.float64)
        Ah.sort_indices()
        self.device = device
        if device:
            # operands on the GPU: the factors, the right-hand side and the
            # solution never leave the card
            import cupy as cp
            import cupyx.scipy.sparse as csp
            self.cp = cp
            self.A = csp.csr_matrix(Ah)
            self._b = cp.zeros((Ah.shape[0], 1))
        else:
            self.A = Ah
            self._b = np.zeros((Ah.shape[0], 1))
        self.s = DirectSolver(self.A, self._b)
        self.s.plan()
        self.s.factorize()

    def solve(self, b):
        if self.device:
            cp = self.cp
            host = isinstance(b, np.ndarray)             # pre-loop checks pass numpy
            bd = cp.ascontiguousarray(cp.asarray(b, dtype=cp.float64).reshape(-1, 1))
            self.s.reset_operands(b=bd)
            x = self.s.solve().ravel()
            cp.cuda.get_current_stream().synchronize()   # honest solve timing
            return cp.asnumpy(x) if host else x
        b2 = np.ascontiguousarray(np.asarray(b, dtype=np.float64).reshape(-1, 1))
        self.s.reset_operands(b=b2)
        return np.asarray(self.s.solve()).ravel()

    def __del__(self):
        try:
            self.s.free()
        except Exception:
            pass


class _PardisoLU:
    def __init__(self, A):
        from pypardiso import PyPardisoSolver
        self.A = sp.csr_matrix(A)
        self.A.sort_indices()
        self.ps = PyPardisoSolver(mtype=11)          # real, nonsymmetric
        self.ps.factorize(self.A)
        self._fast = hasattr(self.ps, '_call_pardiso') and hasattr(self.ps, 'set_phase')

    def solve(self, b):
        b = np.ascontiguousarray(b, dtype=np.float64)
        if self._fast:
            self.ps.set_phase(33)
            return self.ps._call_pardiso(self.A, b)
        return self.ps.solve(self.A, b)


def _growth_report(hist):
    """Fit log-norm growth over the second half of the probe history, for the
    whole-domain ||w|| and for the near-ridge box, where the mode lives."""
    if len(hist) < 4:
        return
    h = np.array(hist)
    k = len(h) // 2
    for col, name in ((3, 'box rms|w|'), (2, 'domain rms|w|')):
        sl = np.polyfit(h[k:, 0], np.log(h[k:, col]), 1)[0]
        ef = (1.0/sl) if sl != 0 else np.inf
        verdict = (f"e-folding {ef:.1f} periods  -> UNSTABLE" if sl > 1e-4 else
                   (f"decay time {-ef:.1f} periods  -> stable" if sl < -1e-4 else
                    "flat (neutral)"))
        print(f"  GROWTH  {name:13s} periods {h[k,0]:.0f}-{h[-1,0]:.0f}: "
              f"rate {sl:+.4f} per period  {verdict}")


def pull(oc, nm):
    oc.eval(f"[ii,jj,vv]=find({nm}); sz=size({nm});")
    return sp.csr_matrix(
        (oc.pull('vv').ravel(),
         (oc.pull('ii').ravel().astype(int) - 1,
          oc.pull('jj').ravel().astype(int) - 1)),
        shape=tuple(oc.pull('sz').ravel().astype(int)))


def splice_bed_rows(L, CG, bedidx, eq='auto'):
    """Replace rows `bedidx` of L with the rows of CG (scaled).

    Returns (L_new, bedsc).  The caller must scale the corresponding rhs
    entries by the SAME bedsc
    scaling an equation and its right-hand side by
    the same number leaves the solution unchanged, which is what makes the
    equilibration bookkeeping rather than a tuned coefficient.

    Kept at module level so it can be tested without Octave or MOLE.
    """
    nc = L.shape[0]
    nbed = CG.shape[0]
    if bedidx.size != nbed:
        raise ValueError(f"{bedidx.size} bed rows vs {nbed} constraints")
    if len(np.unique(bedidx)) != nbed:
        raise ValueError("bed row indices are not distinct")
    L = L.tocsr()
    CG = CG.tocsr()
    if eq == 'auto':
        rmax = np.abs(L).max(axis=1).toarray().ravel()
        ref = np.median(rmax[rmax > 0])
        cmax = np.abs(CG).max(axis=1).toarray().ravel()
        bedsc = ref / np.maximum(cmax, 1e-300)
    else:
        bedsc = np.ones(nbed)
    keep = np.ones(nc)
    keep[bedidx] = 0.0
    Pb = sp.csr_matrix((np.ones(nbed), (bedidx, np.arange(nbed))),
                       shape=(nc, nbed))
    return (sp.diags(keep) @ L + Pb @ (sp.diags(bedsc) @ CG)).tocsr(), bedsc


def grid_diag(X, Z, nx, nz, phi_nh):
    """X, Z are (xi, eta).  Returns True if the grid looks usable."""
    xx = np.gradient(X, axis=0)
    xh = np.gradient(X, axis=1)
    zx = np.gradient(Z, axis=0)
    zh = np.gradient(Z, axis=1)
    J = xx * zh - xh * zx
    a_ = np.stack([xx, zx])
    b_ = np.stack([xh, zh])
    c_ = (a_ * b_).sum(0) / (np.linalg.norm(a_, axis=0) * np.linalg.norm(b_, axis=0) + 1e-30)
    ang = np.degrees(np.arccos(np.clip(c_, -1, 1)))
    ok = True

    sgn = 'ALL +' if (J > 0).all() else ('ALL -' if (J < 0).all()
                                         else f'MIXED -- {int((J<0).sum())} FOLDED CELLS')
    if 'MIXED' in sgn: ok = False
    print(f"  [{el()}] jacobian  : {sgn}   |J| {np.abs(J).min():.4g} .. {np.abs(J).max():.4g}")
    print(f"  [{el()}] grid angle: {ang.min():.1f} - {ang.max():.1f} deg  (90 = orthogonal)")

    wander = np.abs(X[:, 0] - X[:, -1]).max()
    print(f"  [{el()}] xi-line wander top-to-bottom: {wander:.1f} m  "
          f"-> {'FULLY CURVILINEAR' if wander > 1 else 'still a sigma grid'}")

    # Shchepetkin & McWilliams Eq 2.10.  Columns run along ETA for (xi,eta).
    z1 = Z[:-1, :-1]
    z2 = Z[:-1, 1:]
    z3 = Z[1:, :-1]
    z4 = Z[1:, 1:]
    den = np.abs(z4 - z3 + z2 - z1)
    rx = np.abs(z4 + z3 - z2 - z1) / np.maximum(den, 1e-12)
    if den.min() < 1e-9:
        print(f"  [{el()}] r_x       : denominator ~0 -- WRONG AXIS, ignore")
    else:
        bad = rx.max() >= 1.0
        if bad: ok = False
        print(f"  [{el()}] r_x       : max {rx.max():.3f}  median {np.median(rx):.3f}  "
              f"{'*** VIOLATED (>1) ***' if bad else 'OK (<1)'}")

    dx = LX / (nx - 1)
    dz = D0 / (nz - 1)
    he = np.sqrt(3) / np.pi * D0
    lam = dx / he
    print(f"  [{el()}] resolution: dx={dx:.1f} m  dz={dz:.1f} m  aspect {dz/dx:.3f}")
    print(f"  [{el()}] lepticity : h_e={he:.0f} m  lambda=dx/h_e={lam:.4f}  "
          f"Gamma~{lam**2:.4f}  {'OK (<<1)' if lam**2 < 0.1 else '*** MARGINAL ***'}")
    print(f"  [{el()}] beam      : slope {np.tan(np.radians(phi_nh)):.4f}, "
          f"bounce {D0/np.tan(np.radians(phi_nh))/1000:.2f} km, "
          f"{LX/(D0/np.tan(np.radians(phi_nh))):.1f} bounces across the domain")
    return ok


