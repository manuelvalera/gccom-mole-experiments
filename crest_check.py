#!/usr/bin/env python3
"""crest_check.py -- how much ridge does each grid actually represent, and
what --ab would make it exactly the requested height?

  python crest_check.py refit-npz            # report, and write fixedcrest.ps1
  python crest_check.py fixedcrest-npz       # verify the fixed-crest runs

WHY

The beam angle converges at FIRST order to a limit near -1.0 deg at w/N=0.8
(centroid tracker, 0.10-0.40 of a bounce; free-p fit gives p=1.05). That was
confirmed by prediction: from four grids, p=1 predicted +0.19 and +0.00 at
768x301 and 896x351, p=2 predicted +0.43 and +0.35, and the runs gave +0.16
and +0.02.

The seiche, a flat box, converges at SECOND order to zero. So the first-order
offset lives in something the flat box does not have. The cheapest candidate
to isolate is ridge SAMPLING: gridGen samples the Gaussian at node positions,
so the represented crest is below the requested 20 m and creeps up as the
grid refines. That is a convergence process of its own, and it could easily
be first order.

THE TEST

The bottom boundary is z = -(D0 - ab exp(-x^2 / 2 Lb^2)) evaluated at node
positions that do not depend on ab. So the represented crest is exactly
proportional to ab, and ab_needed = ab_used * 20 / crest_represented makes
every grid carry the same 20.00 m crest. Re-run the series that way:

    offset disappears or changes character  -> ridge sampling was the cause
    offset unchanged                        -> it is not sampling; the next
                                               suspect is the curved-bed
                                               treatment itself

The node-independence assumption is checked, not trusted: run this script
again on the fixed-crest output and every grid should report 20.00 m.
"""
import os, sys, glob
import numpy as np

TARGET = 20.0
AB_USED = 20.0


def bottom_row(Z):
    means = [Z[0, :].mean(), Z[-1, :].mean()]
    return Z[0, :] if means[0] < means[1] else Z[-1, :]


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else 'refit-npz'
    files = sorted(glob.glob(os.path.join(d, '*.npz')))
    if not files:
        raise SystemExit(f"no .npz in {d}/")
    rows = []
    for f in files:
        z = np.load(f)
        Z = z['Z']; D0 = float(np.abs(Z).max())
        zb = bottom_row(Z)
        crest = D0 + float(zb.max())
        nz, nx = Z.shape
        rows.append(dict(f=os.path.basename(f), ratio=float(z['ratio']),
                         nx=nx, nz=nz, crest=crest,
                         ab=AB_USED*TARGET/crest if crest > 0 else float('nan')))

    print(f"\n{'file':<24} {'grid':<10} {'crest (m)':<11} {'deficit':<9} {'--ab for 20.00 m'}")
    for r in rows:
        print(f"{r['f']:<24} {r['nx']-1}x{r['nz']-1:<6} {r['crest']:<11.3f} "
              f"{TARGET - r['crest']:<9.3f} {r['ab']:.4f}")

    fixed = [r for r in rows if abs(r['crest'] - TARGET) < 0.005]
    if len(fixed) == len(rows):
        print("\nAll grids carry a 20.00 m crest -- the fixed-crest runs are valid.")
        return

    # write the runner for the w/N=0.8 series using the computed ab per grid
    series = sorted([r for r in rows if abs(r['ratio'] - 0.8) < 1e-9],
                    key=lambda q: q['nx'])
    if not series:
        print("\nno w/N=0.8 fields found; nothing written")
        return
    lines = [
        "# fixedcrest.ps1 -- GENERATED by crest_check.py. Re-runs the w/N=0.8",
        "# series with --ab chosen per grid so every grid carries exactly a",
        "# 20.00 m crest. Verify afterwards with: python crest_check.py fixedcrest-npz",
        "if (-not $env:MOLE_SRC) { Write-Error \"set `$env:MOLE_SRC\"; exit 1 }",
        "$Out = Join-Path (Get-Location) \"fixedcrest-npz\"",
        "if (-not (Test-Path $Out)) { New-Item -ItemType Directory -Path $Out | Out-Null }",
    ]
    for r in series:
        nx, nz, ab = r['nx'], r['nz'], r['ab']
        lines += [
            f"$npz = Join-Path $Out \"f0.8_{nx}x{nz}.npz\"",
            "if (Test-Path $npz) { Write-Host \"   have $npz, skipping\" } else {",
            f"  Write-Host \"-- ratio=0.8  {nx}x{nz}  --ab {ab:.4f}\"",
            "  $t0 = Get-Date",
            "  & python iwbcurv.py --mole $env:MOLE_SRC --beat 9999 `",
            f"      --Lx 6000 --nx {nx} --nz {nz} --ratio 0.8 --ab {ab:.4f} `",
            "      --nper 20 --spp 120 --lsl 0.20 --taus 37.40 `",
            "      --win 75 562 --alpha 1e-6 --forcegrid --out $npz 2>&1 |",
            "    Select-String -Pattern 'BEAM ANGLE|rms residual|max/mean|DIVERGED|\\*\\*\\*' |",
            "    ForEach-Object { Write-Host \"   $($_.Line.TrimEnd())\" }",
            "  Write-Host (\"   took {0:n1} min\" -f ((Get-Date) - $t0).TotalMinutes)",
            "}",
        ]
    lines += [
        "Write-Host \"\"",
        "Write-Host \"now: python crest_check.py fixedcrest-npz\" -ForegroundColor Cyan",
        "Write-Host \"then: python centroid_track.py fixedcrest-npz\" -ForegroundColor Cyan",
    ]
    with open('fixedcrest.ps1', 'w') as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"\nwrote fixedcrest.ps1 for {len(series)} grids at w/N=0.8")


if __name__ == '__main__':
    main()
