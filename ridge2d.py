#!/usr/bin/env python3
"""
ridge2d.py -- internal wave beam generated by an oscillating tidal flow over a
Gaussian ridge.  Reproduces the benchmark of Garcia et al. (2019) sec 3.3,
which follows Vitousek & Fringer (2014).

WHY THIS INSTEAD OF A POINT SOURCE
  A body force in the interior radiates a beam AND a strong forced column at
  the source, and the two are hard to separate.  A ridge generates the beam at
  the topography, with no column, which is why this is the standard benchmark.

CONFIGURATION (Garcia et al. 2019, sec 3.3)
  Lx = 3000 m,  D0 = 1000 m,  ridge  D = D0 - a_b exp(-x^2 / 2 L_b^2)
  a_b = 20 m,   L_b = Lx/100 = 30 m
  N   = 0.007 1/s   (constant stratification)
  forcing  u_bc = u0 sin(omega t),  u0 = 0.01 m/s, at the lateral boundaries
  sponge   SL = -(u - u_bc)/tau_s * sl(r),  sl(r) = exp(-4 r / L_sl)
           tau_s = 100 s,  L_sl = Lx/10
  20 tidal periods; beam angle from the LAST TEN.

MEASUREMENT (their method, not an angular average)
  Find the vertical location of the maximum of the rms velocity in a limited
  horizontal window, then least-squares fit a line to those (x, z) maxima.
  This never averages over angle, so it is immune to near-field contamination.

USAGE
  python ridge2d.py --mole C:/path/to/mole/src/matlab_octave --ratio 0.6
"""
import argparse, os, sys, time

T0 = time.time()
_LAST_BEAT = [time.time()]


def el():
    s_ = time.time() - T0
    h, r = divmod(int(s_), 3600)
    m, sec = divmod(r, 60)
    return f"{h}:{m:02d}:{sec:02d}" if h else f"{m:02d}:{sec:02d}"


def beat(msg, force=False):
    now = time.time()
    if force or now - _LAST_BEAT[0] >= globals().get('_BEAT_EVERY', 300.0):
        _LAST_BEAT[0] = now
        print(f"    [{el()} elapsed] {msg}", flush=True)

_nt = os.environ.get('RIDGE_THREADS', '8')
for _v in ('MKL_NUM_THREADS', 'OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS'):
    os.environ.setdefault(_v, _nt)
os.environ.setdefault('MKL_DYNAMIC', 'FALSE')

import numpy as np
import scipy.sparse as sp
import scipy.sparse.linalg as spl
from oct2py import Oct2Py

LX, D0, AB, LB = 3000.0, 1000.0, 20.0, 30.0
NBV, U0, TAUS = 0.007, 0.01, 100.0


def pull(oc, nm):
    oc.eval(f"[ii,jj,vv]=find({nm}); sz=size({nm});")
    return sp.csr_matrix(
        (oc.pull('vv').ravel(),
         (oc.pull('ii').ravel().astype(int) - 1,
          oc.pull('jj').ravel().astype(int) - 1)),
        shape=tuple(oc.pull('sz').ravel().astype(int)))


def bed(x):
    return D0 - AB * np.exp(-x**2 / (2 * LB**2))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--mole', required=True)
    ap.add_argument('--nx', type=int, default=128)
    ap.add_argument('--nz', type=int, default=101)
    ap.add_argument('--ratio', type=float, default=0.6)
    ap.add_argument('--nper', type=int, default=20)
    ap.add_argument('--spp', type=int, default=120)
    ap.add_argument('--win', type=float, nargs=2, default=[200.0, 500.0],
                    help='horizontal window for the beam fit (m)')
    ap.add_argument('--alpha', type=float, default=1e-4,
                    help='Robin coefficient regularising the pressure system')
    ap.add_argument('--beat', type=float, default=300.0,
                    help='heartbeat interval in seconds (default 300 = 5 min)')
    ap.add_argument('--out', default=None)
    g = ap.parse_args()
    _BEAT_EVERY = g.beat

    om = g.ratio * NBV
    T = 2 * np.pi / om
    phi_nh = np.degrees(np.arcsin(g.ratio))          # nonhydrostatic, Eq. 30
    phi_h = np.degrees(np.arctan(g.ratio))           # hydrostatic,    Eq. 31

    print(f"\n=== ridge2d  omega/N={g.ratio}  {g.nx}x{g.nz}  {g.nper} periods ===")
    print(f"  theory: nonhydrostatic {phi_nh:.2f} deg   hydrostatic {phi_h:.2f} deg")

    # ---- sigma grid conforming to the ridge --------------------------------
    m, n = g.nx - 1, g.nz - 1                        # cells
    xn = np.linspace(-LX/2, LX/2, g.nx)
    sg = np.linspace(0, 1, g.nz)
    XN, SG = np.meshgrid(xn, sg)                     # rows = eta (meshgrid order)
    ZN = -bed(XN) * (1.0 - SG)                       # z = -h at sigma=0, 0 at top
    dx, dz = LX / m, D0 / n
    print(f"  grid: dx={dx:.1f} m  dz={dz:.1f} m  lepticity dz/dx={dz/dx:.3f}")
    # Shchepetkin & McWilliams (2003) Eq. 2.10: hydrostatic consistency.
    # r_x = |z4+z3-z2-z1| / |z4-z3+z2-z1| > 1 means vertical interpolation of
    # density turns into extrapolation, degrading the pressure-gradient force.
    z1 = ZN[:-1, :-1]; z2 = ZN[1:, :-1]; z3 = ZN[:-1, 1:]; z4 = ZN[1:, 1:]
    rx = np.abs(z4+z3-z2-z1) / np.maximum(np.abs(z4-z3+z2-z1), 1e-30)
    print(f"  hydrostatic consistency (S&McW 2003 Eq.2.10): max r_x = "
          f"{rx.max():.3f}  {'OK (<1)' if rx.max() < 1 else '*** VIOLATED ***'}")
    print(f"  ridge: a_b={AB} m on D0={D0} m, max slope "
          f"{np.abs(np.gradient(bed(xn), xn)).max():.4f}, "
          f"beam slope {np.tan(np.radians(phi_nh)):.4f}")

    oc = Oct2Py(); oc.eval("warning('off','all'); more off;"); oc.addpath(g.mole)
    oc.push('X', XN); oc.push('Z', ZN)
    oc.eval(f"k=2; m={m}; n={n}; dx={dx}; dz={dz};")
    oc.eval(f"G=grad2DCurv(k,X,Z); D=div2DCurv(k,X,Z); "
            f"B=robinBC2D(k,m,dx,n,dz,{g.alpha},1); "
            "Ic=interpol2D(m,n,0.5,0.5); Idf=interpolD2D(m,n,0.5,0.5); "
            "J=jacobian2D(k,X,Z);")
    Jv = oc.pull('J').ravel()
    print(f"  jacobian: {'ALL +' if (Jv>0).all() else 'MIXED -- GRID PROBLEM'}"
          f"   |J| {np.abs(Jv).min():.3g} .. {np.abs(Jv).max():.3g}")
    G, D, B, Ic, Idf = [pull(oc, s) for s in ('G', 'D', 'B', 'Ic', 'Idf')]
    oc.exit()

    nu_, nw_ = (m + 1) * n, m * (n + 1)
    nc = (m + 2) * (n + 2)

    L = (D @ G + B).tocsc()
    # Robin, not pure Neumann: pure Neumann leaves L singular (Abouali &
    # Castillo 2014 Eq.10).  alpha=1e-4 -> cond 1.3e14 down to 1.6e2.
    lu = spl.splu(L)
    fk = np.random.default_rng(1).standard_normal(G.shape[0])
    rr = D @ fk
    dv = np.linalg.norm(D @ (fk - G @ lu.solve(rr))) / np.linalg.norm(rr)
    print(f"  Robin alpha={g.alpha:g}   divergence after projection {dv:.2e}  "
          f"{'OK' if dv < 1e-8 else '*** BROKEN ***'}")

    Ic_z = Ic[nu_:, :].tocsr()
    Idf_w = Idf[:, nu_:].tocsr()
    Idf_u = Idf[:, :nu_].tocsr()

    # face / centre physical coordinates
    Zf = 0.5 * (ZN[:, :-1] + ZN[:, 1:])              # (nz) x m -> w-faces
    Xf = 0.5 * (XN[:, :-1] + XN[:, 1:])
    xw = Xf.T.ravel(); zw = Zf.T.ravel()
    Xu = XN[:-1, :] * 0.5 + XN[1:, :] * 0.5
    xu = Xu.T.ravel()

    # sponge, Garcia et al. Eq. 29
    Lsl = LX / 10.0
    r_u = np.minimum(np.abs(xu - xn[0]), np.abs(xu - xn[-1]))
    r_w = np.minimum(np.abs(xw - xn[0]), np.abs(xw - xn[-1]))
    slu = np.exp(-4 * r_u / Lsl); slw = np.exp(-4 * r_w / Lsl)

    dt = T / g.spp
    nt = int(g.nper * T / dt)
    print(f"  [{el()}] dt={dt:.3f} s  ({nt} steps, {g.spp}/period)  T={T:.1f} s")

    beat(f'time loop starting: {nt} steps', force=True)
    u = np.zeros(nu_); w = np.zeros(nw_); b = np.zeros(nc)
    gp = np.zeros(nu_ + nw_)
    acc = np.zeros(nc); nacc = 0
    t0 = time.time()
    for it in range(1, nt + 1):
        t = it * dt
        ubc = U0 * np.sin(om * t)
        bz = Ic_z @ b
        us = u - dt * gp[:nu_] - dt * (u - ubc) / TAUS * slu
        ws = w - dt * gp[nu_:] + dt * bz - dt * w / TAUS * slw
        rhs = (D @ np.concatenate([us, ws])) / dt
        phi = lu.solve(rhs); gphi = G @ phi
        u = us - dt * gphi[:nu_]
        w = ws - dt * gphi[nu_:]
        gp = gp + gphi
        wc = Idf_w @ w
        b = b - dt * NBV**2 * wc
        if t / T > g.nper - 10:
            # total speed, not w alone (avoids sin^2 angular weighting)
            acc += (Idf_u @ u)**2 + wc**2; nacc += 1
        if it % 20 == 0:
            rate = (time.time() - t0) / it
            beat(f"step {it}/{nt} ({100*it/nt:.0f}%)  ETA {(nt-it)*rate/60:.1f} min")
        if it % max(1, nt // 5) == 0:
            print(f"    [{el()}] t/T={t/T:5.1f}  max|u|={np.abs(u).max():.3e}  "
                  f"max|w|={np.abs(w).max():.3e}", flush=True)
            _LAST_BEAT[0] = time.time()

    rms = np.sqrt(acc / max(nacc, 1)).reshape(m + 2, n + 2).T   # (nz+1) x (nx+1)

    # ---- beam angle: ridge track + least squares, Garcia et al. sec 3.3 ----
    xc = np.concatenate(([xn[0]], 0.5 * (xn[:-1] + xn[1:]), [xn[-1]]))
    zcol = -bed(xc)
    pts = []
    for j, xv in enumerate(xc):
        if not (g.win[0] <= abs(xv) <= g.win[1]):
            continue
        col = rms[:, j]
        if not np.isfinite(col).any() or col.max() <= 0:
            continue
        kmax = int(np.nanargmax(col))
        zfrac = kmax / (len(col) - 1)
        pts.append((abs(xv), zcol[j] * (1 - zfrac)))
    if len(pts) < 4:
        print("  too few ridge points for a fit"); return
    P = np.array(pts)
    A = np.vstack([P[:, 0], np.ones(len(P))]).T
    slope, icpt = np.linalg.lstsq(A, P[:, 1], rcond=None)[0]
    meas = np.degrees(np.arctan(abs(slope)))
    res = P[:, 1] - (A @ [slope, icpt])
    print(f"\n  beam fit over |x| in [{g.win[0]:.0f}, {g.win[1]:.0f}] m, "
          f"{len(P)} points, rms residual {np.sqrt(np.mean(res**2)):.1f} m")
    print(f"  BEAM ANGLE  measured {meas:.2f}   nonhydrostatic {phi_nh:.2f}   "
          f"hydrostatic {phi_h:.2f}   error {meas-phi_nh:+.2f} deg "
          f"({100*(meas-phi_nh)/phi_nh:+.1f}%)")
    if g.out:
        np.savez_compressed(g.out, rms=rms, xc=xc, ZN=ZN, XN=XN,
                            ratio=g.ratio, pts=P)
        print(f"  saved {g.out}")
    print(f"\n  total wall time {el()}")


if __name__ == '__main__':
    main()
